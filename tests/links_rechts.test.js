const H = require('./hulp');
const { chromium } = H;
const D = H.data('snoei_test'), U = H.UIT;
(async () => {
  await H.start();
  const b = await chromium.launch({ ...H.browserOpties(), args: ['--no-sandbox'] });
  const ctx = await b.newContext({ viewport: { width: 1600, height: 950 }, acceptDownloads: true });
  const p = await ctx.newPage(); p.setDefaultTimeout(120000);
  const fouten = []; p.on('pageerror', e => fouten.push(e.message));
  await p.route(/pdok\.nl/, r => r.abort());
  await p.addInitScript(() => { window.showDirectoryPicker = async () => { const r = await navigator.storage.getDirectory(); return r.getDirectoryHandle('lrproj', { create: true }); }; });
  await p.goto(H.URL);
  await p.evaluate(async () => { const r = await navigator.storage.getDirectory(); try { await r.removeEntry('lrproj', { recursive: true }); } catch {} });
  await p.reload();
  const st = async () => (await p.textContent('#status')).trim();
  const wacht = async (re, max = 480) => { for (let i = 0; i < max; i++) { const s = await st(); if (re.test(s) || fouten.length) return s; await p.waitForTimeout(250); } return await st(); };
  await p.setInputFiles('#ptsBestand', D + '/bospad_scan.pts');
  await p.waitForSelector('#projectMapDialoog[open]'); await p.click('#pmKies');
  await wacht(/driehoeken/);
  await p.setInputFiles('#asBestand', D + '/as_schouwpad.geojson'); await p.waitForTimeout(800);
  await wacht(/Profielen uit alle .* punten ·/);
  console.log('symmetrisch:', JSON.stringify(await p.evaluate(() => window.__pvTest.dwars())), '| breedte', await p.inputValue('#dwarsBreedte'));
  await p.fill('#dwarsLinks', '3'); await p.dispatchEvent('#dwarsLinks', 'change');
  await p.fill('#dwarsRechts', '12'); await p.dispatchEvent('#dwarsRechts', 'change');
  await p.waitForTimeout(300);
  console.log('direct:', JSON.stringify(await p.evaluate(() => window.__pvTest.dwars())), '| breedte', await p.inputValue('#dwarsBreedte'));
  console.log('alle punten:', (await wacht(/Profielen uit alle .* punten ·/)).slice(0, 90));
  await p.waitForTimeout(500);
  console.log('na alle punten:', JSON.stringify(await p.evaluate(() => window.__pvTest.dwars())));
  await p.screenshot({ path: H.UIT + '/lr.png' });
  await p.click('#printKnop'); await p.waitForTimeout(400);
  await p.evaluate(() => { const z = (k, v) => { const e = document.getElementById(k); if (typeof v === 'boolean') e.checked = v; else e.value = v; e.dispatchEvent(new Event('change')); }; z('pdfLuchtfoto', false); z('pdfFormaat', 'A3'); z('pdf3D', false); });
  await p.click('#pdfMaak'); console.log('pdf:', (await wacht(/Opgeslagen.*pdf|mislukt/)).slice(0, 120));
  await p.click('#dxfKnop'); console.log('dxf:', (await wacht(/Opgeslagen.*dxf|mislukt/)).slice(0, 120));
  await p.click('#ifcKnop'); console.log('ifc:', (await wacht(/Opgeslagen.*ifc|mislukt/)).slice(0, 120));
  await p.keyboard.press('Control+S'); await wacht(/Opgeslagen: lrproj/);
  await p.reload(); await p.waitForTimeout(800);
  await p.click('#projectOpenKnop'); await p.waitForSelector('#projectOpenDialoog[open]'); await p.click('#poRecent button');
  await wacht(/driehoeken/); await p.waitForTimeout(1500);
  console.log('na openen: links', await p.inputValue('#dwarsLinks'), 'rechts', await p.inputValue('#dwarsRechts'), JSON.stringify(await p.evaluate(() => window.__pvTest.dwars())));
  console.log('fouten:', fouten.join(' | ') || 'geen');
  await b.close();
})();
